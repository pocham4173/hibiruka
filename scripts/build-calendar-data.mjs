// Node 24+, TZ=Asia/Tokyo. Input: Cabinet Office syukujitsu.csv (Shift_JIS).
import fs from 'node:fs';
import Lunar from './vendor/JapaneseLunisolarCalendar.ts';
if (process.env.TZ !== 'Asia/Tokyo') throw Error('Run with TZ=Asia/Tokyo');
const input = process.argv[2];
if (!input) throw Error('Pass the downloaded Cabinet Office CSV path');
const holidays = {};
for (const line of new TextDecoder('shift_jis').decode(fs.readFileSync(input)).split(/\r?\n/).slice(1)) {
  const [date, name] = line.split(',');
  if (!/^\d{4}\/\d{1,2}\/\d{1,2}$/.test(date || '')) continue;
  const [y,m,d] = date.split('/');
  holidays[`${y}-${m.padStart(2,'0')}-${d.padStart(2,'0')}`] = name;
}
const rokuyo = {};
for (let y=2020; y<=2032; y++) for (let m=1; m<=12; m++) {
  let days = '';
  for (let d=1; d<=new Date(y,m,0).getDate(); d++) {
    const lunar = new Lunar(new Date(y,m-1,d));
    days += (lunar.month + lunar.day - 2) % 6;
  }
  rokuyo[`${y}-${String(m).padStart(2,'0')}`] = days;
}
const years = Object.keys(holidays).map(x=>+x.slice(0,4));
const data = {holidayFrom:Math.min(...years),holidayThrough:Math.max(...years),holidays,rokuyo};
fs.writeFileSync('index/index/calendar-data.js', '// Generated by scripts/build-calendar-data.mjs; see docs/personal-calendar.md for sources.\n' +
  'globalThis.HibirukaCalendarData = ' + JSON.stringify(data) + ';\n');
